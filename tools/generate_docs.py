def render_glossary(rid: str) -> str:
    r = REGISTRY[rid]
    out = [GEN_NOTE, f"# {rid} — Glossary\n\n"]
    if r["glossary"]:
        out.append("| Term | Definition |\n|---|---|\n")
        for term, d in r["glossary"]:
            out.append(f"| {term} | {d} |\n")
    else:
        out.append("See the [master glossary](../../glossary/README.md).\n")
    out.append("\nSee also the [master glossary](../../glossary/README.md).\n")
    return "".join(out)


