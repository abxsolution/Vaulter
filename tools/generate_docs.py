    for rid in all_rfc_ids():
        for dep in REGISTRY[rid]["depends_on"]:
            edges.append(f"  {dep} --> {rid}")
    code = "flowchart LR\n" + "\n".join(sorted(set(edges)))
    out.append(mermaid(code))
    out.append("\n> Navigation: [Architecture Index](./README.md)\n")
    return "".join(out)


