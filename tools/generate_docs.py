def render_glossary_master() -> str:
    terms = {}
    for rid in all_rfc_ids():
        for term, d in REGISTRY[rid]["glossary"]:
            terms.setdefault(term, (d, rid))
    # curated core terms
    core = {
        "BSV": ("Bithat Secure Vault, the offline-first infrastructure asset vault.", "RFC-0001"),
        "Vault": ("The encrypted repository of objects.", "RFC-0005"),
        "Object": ("The uniform unit of storage.", "RFC-0025"),
        "AEAD": ("Authenticated Encryption with Associated Data.", "RFC-0003"),
        "Argon2id": ("Memory-hard password-based key derivation function.", "RFC-0003"),
        "AES-256-GCM": ("Authenticated symmetric cipher used by BSV.", "RFC-0003"),
    }
    terms = {**core, **terms}
    out = [GEN_NOTE, "# Master Glossary\n\n",
           "Canonical terminology for the BSV architecture. Per-RFC glossaries "
           "link back here.\n\n", "| Term | Definition | Source |\n|---|---|---|\n"]
    for term in sorted(terms, key=str.lower):
        d, rid = terms[term]
        out.append(f"| {term} | {d} | [{rid}](../rfcs/{rid}/README.md) |\n")
    out.append("\n> Navigation: [Architecture Index](../architecture/README.md)\n")
    return "".join(out)


