#!/usr/bin/env python3
"""
generate_docs.py — Bithat Secure Vault (BSV) architecture repository generator.

Renders the entire docs/ tree from tools/rfc_registry.py: directory READMEs,
the RFC index and per-RFC scaffolds, cross-references and dependency diagrams,
the full set of architecture indexes, reusable templates, ADRs, cross-cutting
Mermaid diagrams, the architecture review, and the implementation roadmap.

Idempotent. Never touches ROADMAP.md or the migrated part files produced by
split_roadmap.py (it only writes READMEs/references/glossaries for those RFCs).

Usage:  python3 tools/generate_docs.py
"""
from __future__ import annotations

from pathlib import Path

from rfc_registry import (
    REGISTRY, MIGRATED_PARTS, all_rfc_ids, CATEGORIES, STATUS,
)

REPO = Path(__file__).resolve().parents[1]
DOCS = REPO / "docs"

# --- normative helpers -----------------------------------------------------

GEN_NOTE = (
    "<!-- GENERATED by tools/generate_docs.py from tools/rfc_registry.py. "
    "Edit the registry and regenerate; do not hand-edit generated files. -->\n"
)


def mermaid(code: str) -> str:
    return "```mermaid\n" + code.rstrip() + "\n```\n"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not text.endswith("\n"):
        text += "\n"
    path.write_text(text, encoding="utf-8")


def title_of(rid: str) -> str:
    return REGISTRY[rid]["title"]


def link_rfc(rid: str, from_dir_depth_to_rfcs: str = "..") -> str:
    """Markdown link to an RFC README relative to docs/rfcs/."""
    return f"[{rid} — {title_of(rid)}]({from_dir_depth_to_rfcs}/{rid}/README.md)"


# --- reverse cross-reference derivation ------------------------------------

def derive_relationships():
    """Ensure depends_on/consumed_by and uses/used_by are bidirectional."""
    for rid, r in REGISTRY.items():
        for dep in r["depends_on"]:
            if dep in REGISTRY and rid not in REGISTRY[dep]["consumed_by"]:
                REGISTRY[dep]["consumed_by"].append(rid)
        for u in r["uses"]:
            if u in REGISTRY and rid not in REGISTRY[u]["used_by"]:
                REGISTRY[u]["used_by"].append(rid)
    for rid, r in REGISTRY.items():
        for k in ("depends_on", "consumed_by", "uses", "used_by",
                  "implemented_by"):
            r[k] = sorted(set(x for x in r[k] if x in REGISTRY))


# --- per-RFC rendering -----------------------------------------------------

def render_crossrefs(rid: str) -> str:
    r = REGISTRY[rid]
    lines = ["## Cross-References\n"]

    def block(label, ids):
        if not ids:
            return f"- **{label}:** _none_\n"
        return f"- **{label}:** " + ", ".join(
            f"[{i}](../{i}/README.md)" for i in ids) + "\n"

    lines.append(block("Depends on", r["depends_on"]))
    lines.append(block("Consumed by", r["consumed_by"]))
    lines.append(block("Uses", r["uses"]))
    lines.append(block("Used by", r["used_by"]))
    lines.append(block("Implemented by", r["implemented_by"]))
    return "".join(lines) + "\n"


def render_dependency_diagram(rid: str) -> str:
    r = REGISTRY[rid]
    edges = []
    for dep in r["depends_on"]:
        edges.append(f"  {dep} --> {rid}")
    for c in r["consumed_by"]:
        edges.append(f"  {rid} --> {c}")
    if not edges:
        edges.append(f"  {rid}")
    code = "flowchart LR\n" + "\n".join(sorted(set(edges)))
    return mermaid(code)


def render_existing_readme(rid: str) -> str:
    r = REGISTRY[rid]
    parts = MIGRATED_PARTS.get(rid, [])
    out = [GEN_NOTE, f"# {rid} — {r['title']}\n"]
    out.append(f"| Field | Value |\n|---|---|\n")
    out.append(f"| RFC | {rid} |\n")
    out.append(f"| Category | {r['category']} |\n")
    out.append(f"| Status | {STATUS[r['status']]} |\n")
    out.append(f"| Origin | Migrated verbatim from `ROADMAP.md` |\n")
    out.append(f"| Parts | {len(parts)} |\n\n")
    out.append("## Abstract\n\n" + r["abstract"] + "\n\n")
    out.append("## Parts\n\n")
    for i, pt in enumerate(parts, 1):
        out.append(f"{i}. [Part {i:02d} — {pt}](./part-{i:02d}.md)\n")
    out.append("\n")
    if rid == "RFC-0004":
        out.append(
            "> **Review note:** This RFC is under-developed in the source "
            "(single part). See the "
            "[Architecture Review](../../architecture/ARCHITECTURE-REVIEW.md) "
            "for the expansion backlog (passkey ceremony, recovery flow, "
            "session bootstrap, enterprise SSO).\n\n")
    out.append(render_crossrefs(rid))
    out.append("## Dependency Diagram\n\n")
    out.append(render_dependency_diagram(rid))
    out.append("\n## Supporting Documents\n\n")
    out.append("- [References](./references.md)\n- [Glossary](./glossary.md)\n"
               "- [Diagrams](./diagrams/)\n- [Images](./images/)\n\n")
    out.append("---\n\n> Navigation: [RFC Index](../README.md) · "
               "[Architecture Index](../../architecture/README.md)\n")
    return "".join(out)


def render_new_proposal_body(rid: str) -> str:
    """The normative proposal (part-01.md) for a new RFC."""
    r = REGISTRY[rid]
    out = [
        f"---\nrfc: {rid}\ntitle: {r['title']}\npart: 1\n"
        f"part_title: Design Proposal\nstatus: {STATUS[r['status']]}\n"
        f"classification: Internal\n---\n\n",
        f"# {rid} — {r['title']}\n\n",
        "## Part 1 of 1 — Design Proposal\n\n",
        "> Navigation: [RFC Home](./README.md) · [RFC Index](../README.md) · "
        "[Architecture Index](../../architecture/README.md)\n\n---\n\n",
        "# 1. Abstract\n\n" + r["abstract"] + "\n\n",
        "# 2. Status & Motivation\n\n"
        f"This RFC was introduced during the architecture consolidation of "
        f"the BSV platform. It formalizes capabilities that were previously "
        f"referenced by other RFCs but never specified. See the "
        f"[Architecture Review](../../architecture/ARCHITECTURE-REVIEW.md).\n\n",
    ]
    sec = 3
    if r["goals"]:
        out.append(f"# {sec}. Goals\n\n")
        for g in r["goals"]:
            out.append(f"- {g}\n")
        out.append("\n")
        sec += 1
    for title, paras in r["sections"]:
        out.append(f"# {sec}. {title}\n\n")
        for p in paras:
            out.append(p + "\n\n")
        sec += 1
    if r["requirements"]:
        out.append(f"# {sec}. Requirements\n\n")
        for req in r["requirements"]:
            out.append(f"- {req}\n")
        out.append("\n")
        sec += 1
    if r["diagrams"]:
        out.append(f"# {sec}. Diagrams\n\n")
        for d in r["diagrams"]:
            out.append(f"### {d['title']}\n\n")
            out.append(mermaid(d["mermaid"]) + "\n")
        sec += 1
    out.append(f"# {sec}. Cross-References\n\n")
    out.append(render_crossrefs(rid))
    out.append(f"# {sec + 1}. Open Questions & Future Work\n\n")
    out.append("- Refine acceptance criteria with the implementation team.\n")
    out.append("- Add sequence-level detail as dependent RFCs stabilize.\n\n")
    out.append("---\n\n> End of " + rid + " Part 1\n")
    return "".join(out)


