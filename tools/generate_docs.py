def render_roadmap() -> str:
    out = [GEN_NOTE, "# Implementation Roadmap\n\n",
           "Phased technical roadmap. Each phase defines inputs, outputs, "
           "dependencies, deliverables, risks, and exit criteria. This is a "
           "documentation/planning artifact; **no application code is part of "
           "this repository**.\n\n"]
    out.append(mermaid(
        "flowchart TB\n" + "\n".join(
            f"  P{i}[{p[0]}]" for i, p in enumerate(PHASES)) + "\n" +
        "\n".join(f"  P{i} --> P{i+1}" for i in range(len(PHASES) - 1))))
    out.append("\n")
    for i, (name, inp, outp, deps, deliv, risks, exitc) in enumerate(PHASES, 1):
        out.append(f"## Phase {i}: {name}\n\n"
                   f"- **Inputs:** {inp}\n"
                   f"- **Outputs:** {outp}\n"
                   f"- **Dependencies:** {deps}\n"
                   f"- **Deliverables:** {deliv}\n"
                   f"- **Risks:** {risks}\n"
                   f"- **Exit Criteria:** {exitc}\n\n")
    out.append("> Navigation: [Architecture Index](./README.md)\n")
    return "".join(out)


# --- main ------------------------------------------------------------------

def main() -> None:
    derive_relationships()

    # top-level
    write(DOCS / "README.md", render_docs_home())

    # architecture indexes + planning
    write(DOCS / "architecture" / "README.md", render_architecture_index())
    write(DOCS / "architecture" / "component-index.md", render_component_index())
    write(DOCS / "architecture" / "security-index.md", render_security_index())
    write(DOCS / "architecture" / "threat-index.md", render_threat_index())
    write(DOCS / "architecture" / "storage-index.md", render_storage_index())
    write(DOCS / "architecture" / "dependency-graph.md", render_dependency_graph())
    write(DOCS / "architecture" / "ARCHITECTURE-REVIEW.md", render_review())
    write(DOCS / "architecture" / "implementation-roadmap.md", render_roadmap())

    # rfc index
    write(DOCS / "rfcs" / "README.md", render_rfc_index())

    # per-RFC
    for rid in all_rfc_ids():
        r = REGISTRY[rid]
        base = DOCS / "rfcs" / rid
        (base / "diagrams").mkdir(parents=True, exist_ok=True)
        (base / "images").mkdir(parents=True, exist_ok=True)
        write(base / "references.md", render_references(rid))
        write(base / "glossary.md", render_glossary(rid))
        (base / "images" / ".gitkeep").write_text("", encoding="utf-8")
        if r["existing"]:
            write(base / "README.md", render_existing_readme(rid))
        else:
            write(base / "README.md", render_new_readme(rid))
            write(base / "part-01.md", render_new_proposal_body(rid))
            for d in r["diagrams"]:
                write(base / "diagrams" / f"{d['name']}.md",
                      render_rfc_diagram_file(rid, d))
        # keep diagrams dir non-empty for existing RFCs too
        if not r["diagrams"]:
            (base / "diagrams" / ".gitkeep").write_text("", encoding="utf-8")

    # cross-cutting diagrams
    write(DOCS / "diagrams" / "README.md", render_diagram_index())
    for name, title, code in CROSS_DIAGRAMS:
        write(DOCS / "diagrams" / f"{name}.md",
              render_cross_diagram(name, title, code))

    # adr + decisions
    write(DOCS / "decisions" / "README.md", render_decision_index())
    for i, (t, d) in enumerate(ADRS, 1):
        write(DOCS / "adr" / f"ADR-{i:04d}.md", render_adr(i, t, d))
    write(DOCS / "adr" / "README.md",
          GEN_NOTE + "# Architecture Decision Records\n\n"
          "See the [Decision Index](../decisions/README.md) for the full list. "
          "ADRs 0001–0020 are the ratified Security Architecture Decisions "
          "from [RFC-0002 Part 9](../rfcs/RFC-0002/part-09.md).\n")

    # glossary
    write(DOCS / "glossary" / "README.md", render_glossary_master())

    # templates
    tpl_index = [GEN_NOTE, "# Templates\n\nReusable templates for consistent "
                 "authoring. Copy and fill in.\n\n"]
    for fn in sorted(TEMPLATES):
        tpl_index.append(f"- [{fn}](./{fn})\n")
        write(DOCS / "templates" / fn, TEMPLATES[fn])
    write(DOCS / "templates" / "README.md", "".join(tpl_index))

    # simple directory READMEs
    for d, (title, body) in DIR_READMES.items():
        write(DOCS / d / "README.md", GEN_NOTE + f"# {title}\n\n" + body +
              "\n> Navigation: [Architecture Index](../architecture/README.md)\n")

    print("Documentation generation complete.")


if __name__ == "__main__":
    main()
