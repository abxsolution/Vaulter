def render_rfc_index() -> str:
    out = [GEN_NOTE, "# RFC Index\n\n",
           "Authoritative index of every Request for Comments (RFC) in the "
           "Bithat Secure Vault architecture. RFC numbering is canonical and "
           "governed by [RFC-0029 Architecture Governance](./RFC-0029/README.md).\n\n"]
    out.append("| RFC | Title | Category | Status | Origin |\n")
    out.append("|---|---|---|---|---|\n")
    for rid in all_rfc_ids():
        r = REGISTRY[rid]
        origin = "Migrated" if r["existing"] else "New proposal"
        out.append(f"| [{rid}](./{rid}/README.md) | {r['title']} | "
                   f"{r['category']} | {STATUS[r['status']]} | {origin} |\n")
    out.append("\n## By Category\n\n")
    for cat in CATEGORIES:
        ids = [i for i in all_rfc_ids() if REGISTRY[i]["category"] == cat]
        if ids:
            out.append(f"- **{cat}:** " +
                       ", ".join(f"[{i}](./{i}/README.md)" for i in ids) + "\n")
    out.append("\n> Navigation: [Architecture Index](../architecture/README.md)"
               " · [Docs Home](../README.md)\n")
    return "".join(out)


def render_dependency_graph() -> str:
    out = [GEN_NOTE, "# RFC Dependency Graph\n\n",
           "Global dependency graph across all RFCs. An arrow `A --> B` means "
           "*B depends on A* (A is consumed by B).\n\n"]
